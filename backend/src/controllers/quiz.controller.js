export const getMyQuizzes = async (req, res) => {
  try {
    const userId = req.user.id;

    // --------------------------------------------------
    // 1. Get all quizzes generated by logged-in user
    // --------------------------------------------------
    const quizzes = await Quiz.find({
      user: userId,
    }).sort({
      createdAt: -1,
    });

    // --------------------------------------------------
    // 2. Get attempts for those quizzes
    // --------------------------------------------------
    const quizIds = quizzes.map((quiz) => quiz._id);

    const attempts = await Attempt.find({
      user: userId,
      quiz: {
        $in: quizIds,
      },
    });

    // --------------------------------------------------
    // 3. Update expired attempts
    //
    // If attempt is still IN_PROGRESS
    // but expiresAt has already passed,
    // update its status to EXPIRED.
    // --------------------------------------------------
    const now = new Date();

    for (const attempt of attempts) {
      if (
        attempt.status === "IN_PROGRESS" &&
        attempt.expiresAt &&
        attempt.expiresAt < now
      ) {
        attempt.status = "EXPIRED";
        await attempt.save();
      }
    }

    // --------------------------------------------------
    // 4. Create quick lookup map
    //
    // quizId -> attempt
    // --------------------------------------------------
    const attemptMap = {};

    attempts.forEach((attempt) => {
      attemptMap[attempt.quiz.toString()] = attempt;
    });

    // --------------------------------------------------
    // 5. Prepare frontend response
    // --------------------------------------------------
    const data = quizzes.map((quiz) => {
      const attempt = attemptMap[quiz._id.toString()];

      return {
        _id: quiz._id,

        title: quiz.title,

        topic: quiz.topic,

        difficulty: quiz.difficulty,

        totalQuestions: quiz.questions.length,

        createdAt: quiz.createdAt,

        // If attempt does not exist yet,
        // keep status as IN_PROGRESS for current flow
        status: attempt
          ? attempt.status
          : "NOT_STARTED",

        // Score only matters for completed quiz
        score:
          attempt?.status === "COMPLETED"
            ? attempt.score
            : null,

        // Percentage only matters for completed quiz
        percentage:
          attempt?.status === "COMPLETED"
            ? attempt.percentage
            : null,
      };
    });

    // --------------------------------------------------
    // 6. Send response
    // --------------------------------------------------
    return res.status(200).json({
      quizzes: data,
    });

  } catch (error) {
    // console.log("Get My Quizzes Error:", error);

    return res.status(500).json({
      message: "Internal server error",
    });
  }
};

export const getQuiz = async (req, res) => {

  try {

    const userId = req.user.id;
    const { quizId } = req.params;

    const quiz = await Quiz.findOne({
      _id: quizId,
      user: userId,
    });

    if (!quiz) {
      return res.status(404).json({
        message: "Quiz not found",
      });
    }

    return res.status(200).json({
      message: "Quiz fetched successfully",
      quiz,
    });

  } catch (error) {

    // console.error("Get Quiz Error:", error);

    return res.status(500).json({
      message: "Failed to fetch quiz",
    });

  }

};

